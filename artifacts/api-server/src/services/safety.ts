/**
 * Keywords that indicate a self-diagnosis or treatment-seeking request, which
 * the assistant must refuse to answer.
 */
const SYMPTOM_KEYWORDS = [
  "симптом",
  "болить",
  "біль у",
  "у мене",
  "в мене",
  "що приймати",
  "що випити",
  "що пити",
  "чим лікувати",
  "як лікувати",
  "лікування від",
  "вилікувати",
  "діагноз",
  "температура",
  "висип",
  "нудить",
  "блює",
  "пронос",
  "кашель",
  "нежить",
  "горло",
  "застуда",
  "грип",
  "тиск піднявся",
  "що мені робити",
  "порадьте препарат",
  "порадь препарат",
  "порадьте ліки",
  "призначте",
  "пропишіть",
  "що допоможе від",
  "яка доза",
  "доза для",
  "можна дитині",
  "чи можна скасувати",
  "скасувати препарат",
  "скасувати ліки",
];

export function isTreatmentRequest(text: string | undefined | null): boolean {
  if (!text) return false;
  const normalized = text.toLowerCase();
  return SYMPTOM_KEYWORDS.some((kw) => normalized.includes(kw));
}
